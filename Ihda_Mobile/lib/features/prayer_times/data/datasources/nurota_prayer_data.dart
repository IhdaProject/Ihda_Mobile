  /// Returns exact Nurota prayer day if data exists for [date], else null.
  static PrayerDay? getPrayerDayForNurota(DateTime date) {
    final monthMap = _timetable[date.month];
    if (monthMap == null) return null;

    final times = monthMap[date.day];
    if (times == null || times.length != 12) return null;

    final fajr = DateTime(date.year, date.month, date.day, times[0], times[1]);
    final sunrise = DateTime(date.year, date.month, date.day, times[2], times[3])
        .subtract(const Duration(minutes: 15));
    final dhuhr = DateTime(date.year, date.month, date.day, times[4], times[5]);
    final asr = DateTime(date.year, date.month, date.day, times[6], times[7]);
    final maghrib = DateTime(date.year, date.month, date.day, times[8], times[9]);
    final isha = DateTime(date.year, date.month, date.day, times[10], times[11]);

    return PrayerDay(
      date: date,
      prayers: [
        Prayer(type: PrayerType.fajr, time: fajr),
        Prayer(type: PrayerType.sunrise, time: sunrise),
        Prayer(type: PrayerType.dhuhr, time: dhuhr),
        Prayer(type: PrayerType.asr, time: asr),
        Prayer(type: PrayerType.maghrib, time: maghrib),
        Prayer(type: PrayerType.isha, time: isha),
      ],
    );
  }
